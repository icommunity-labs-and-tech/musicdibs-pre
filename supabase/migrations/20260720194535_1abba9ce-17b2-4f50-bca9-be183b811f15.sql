<ul>
<li><strong>Song registration</strong> proves <em>who created the work</em> and <em>when</em>.</li>
<li><strong>Music publishers</strong> and PROs help you <em>collect royalties</em> once the work is exploited.</li>
</ul>
<p>Before you approach any publisher, PRO or label, you should already have solid registration evidence. That is exactly what Musicdibs delivers in minutes.</p>

